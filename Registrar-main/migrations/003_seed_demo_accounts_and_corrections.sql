create table if not exists public.record_corrections (
  id bigint generated by default as identity primary key,
  tracking_code text unique not null,
  student_id bigint not null references public.users(id) on delete cascade,
  category text not null,
  current_value text not null,
  proposed_value text not null,
  contact_number text not null,
  reason text not null,
  supporting_documents jsonb,
  status text not null default 'Pending Review',
  registrar_remarks text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.record_corrections enable row level security;
grant select, insert, update, delete on public.record_corrections to service_role;
grant usage, select on sequence public.record_corrections_id_seq to service_role;

