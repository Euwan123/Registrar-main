create table if not exists public.users (
  id bigint generated by default as identity primary key,
  university_id text unique not null,
  first_name text not null,
  last_name text not null,
  email text unique not null,
  password_hash text not null,
  role text not null default 'student',
  college text,
  program text,
  created_at timestamptz not null default now()
);

create table if not exists public.document_types (
  id bigint generated by default as identity primary key,
  category text not null,
  name text unique not null,
  base_fee numeric(10,2) not null default 0,
  is_active boolean not null default true
);

create table if not exists public.requests (
  id bigint generated by default as identity primary key,
  tracking_code text unique not null,
  student_id bigint not null references public.users(id) on delete cascade,
  fulfillment_method text not null,
  payment_method text not null,
  total_fee numeric(10,2) not null,
  status text not null default 'Pending Review',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.request_items (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.requests(id) on delete cascade,
  document_id bigint not null references public.document_types(id) on delete restrict,
  copies integer not null default 1
);

alter table public.users enable row level security;
alter table public.document_types enable row level security;
alter table public.requests enable row level security;
alter table public.request_items enable row level security;

grant usage on schema public to service_role;
grant select, insert, update, delete on
  public.users,
  public.document_types,
  public.requests,
  public.request_items
to service_role;
grant usage, select on sequence
  public.users_id_seq,
  public.document_types_id_seq,
  public.requests_id_seq,
  public.request_items_id_seq
to service_role;

